"use strict";
// COORD-958: ONE engine-surface integrity check. It replaces the two guards `template-sync`
// (manifest-vs-files, COORD-606/607) and `engine-pin` (pin-vs-surface drift, ENT-011/COORD-677).
// Every ticket regenerates both in the same final commit, so the two are one step:
//
//   regenerateAndVerify  re-stamps coord/TEMPLATE_SYNC_MANIFEST.json from the target tree's own
//                        bytes, re-pins coord/engine-pin.json, then verifies BOTH surfaces again
//                        from disk and refuses unless they agree. It is the only mutating step.
//   evaluateTemplateSync read-only manifest-vs-files evaluation (check-template-sync.sh and the
//                        audit of engine-managed files, COORD-607).
//   engineSurfaceProblems read-only Repo-X closeout verdict over the same two surfaces (COORD-591).
//
// Old refusal wording and problem codes are kept verbatim as aliases, so a refusal reads the same:
//   template-sync  -> "check-template-sync drift" (failure kinds: missing, checksum-drift, untracked)
//   engine-pin     -> "verify-engine drift" (problem codes: no_pin, manifest_fingerprint_drift,
//                     engine_file_drift; file kinds: added, removed, missing, appeared, changed, mode-changed)
// Failure mode "stale checksum after a squash merge": regenerateAndVerify derives every checksum
// from the bytes on disk at run time and then re-reads them, so a manifest that carries a stale
// checksum cannot survive the step. Failure mode "post-merge edit not re-stamped": the step is one
// command, so re-running it after any edit re-stamps everything, and verifyOnly refuses until it is.
// Target safety: a ticket worktree target may only be regenerated by that worktree's own copy;
// running the canonical checkout's script against a ticket worktree is refused (field evidence
// 2026-11-12: four workers re-pinned ROOT and stranded their branches).

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { execFileSync } = require("node:child_process");
const discovery = require("./template-sync-discovery.js");
const createEnginePin = require("./engine-pin.js");

const MANIFEST_REL = "coord/TEMPLATE_SYNC_MANIFEST.json";
const TICKET_WORKTREE = /\/coord\/\.worktrees\/[^/]+\/[^/]+$/;

class EngineSurfaceRefusal extends Error {}

function fail(message) {
  throw new EngineSurfaceRefusal(message);
}

function toPosix(p) {
  return path.resolve(p).split(path.sep).join("/");
}

// guard:engine-surface-integrity
function isTicketWorktree(root) {
  return TICKET_WORKTREE.test(toPosix(root));
}

// Pure: a ticket-worktree target can only be regenerated by its own script copy.
function refuseCanonicalTarget(invokedRoot, targetRoot) {
  const invoked = path.resolve(invokedRoot);
  const target = path.resolve(targetRoot);
  if (isTicketWorktree(target) && invoked !== target) {
    // guard:engine-surface-integrity
    fail(
      `verify-engine --regenerate refused: the target ${target} is a ticket worktree, but this script ` +
        `runs from the canonical checkout ${invoked}. Run the worktree's own copy from inside the worktree ` +
        "(cd <worktree> && coord/scripts/gov verify-engine --regenerate); the canonical manifest and pin must stay untouched (COORD-958)."
    );
  }
}

function gitToplevel(cwd) {
  try {
    return execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).replace(/\n$/, "") || null;
  } catch {
    return null;
  }
}

function readJson(absPath, label) {
  let raw;
  try {
    raw = fs.readFileSync(absPath, "utf8");
  } catch (error) {
    fail(`Could not read ${label} at ${absPath}: ${error.message}`);
  }
  try {
    return JSON.parse(raw);
  } catch (error) {
    fail(`Could not parse ${label} at ${absPath}: ${error.message}`);
  }
}

function checksumFile(absPath) {
  const bytes = fs.readFileSync(absPath);
  return { algo: "sha256", hex: crypto.createHash("sha256").update(bytes).digest("hex"), bytes: bytes.length };
}

function relativeToRepo(repoRoot, absPath) {
  const relative = path.relative(repoRoot, absPath);
  return relative && !relative.startsWith("..") ? relative : absPath;
}

// template-sync: the manifest-vs-files rule. Pure over the disk; returns the summary the
// check-template-sync.sh formatter prints, or throws EngineSurfaceRefusal for a manifest error.
function evaluateTemplateSync({ repoRoot, manifestPath, strict = false, auditCoverage = false }) {
  const root = path.resolve(repoRoot);
  const manifest = readJson(path.resolve(manifestPath), "template sync manifest");
  if (manifest.schema_version !== 1) fail(`Unsupported manifest schema_version ${JSON.stringify(manifest.schema_version)}.`);
  if (!Array.isArray(manifest.items) || manifest.items.length === 0) fail("Manifest must contain a non-empty items array.");

  const seenPaths = new Set();
  const results = [];
  const failures = [];
  const warnings = [];
  for (const item of manifest.items) {
    if (!item || typeof item.path !== "string" || item.path.trim() === "") fail("Manifest item is missing a non-empty path.");
    if (seenPaths.has(item.path)) fail(`Manifest contains duplicate path ${item.path}.`);
    seenPaths.add(item.path);
    const policy = item.match_policy === "advisory" ? "advisory" : "exact";
    const absPath = path.join(root, item.path);
    const expected = item.checksum || null;
    if (!expected || expected.algo !== "sha256" || typeof expected.hex !== "string" || !Number.isInteger(expected.bytes)) {
      fail(`Manifest item ${item.path} is missing a valid sha256 checksum contract.`);
    }
    const entry = { path: item.path, policy, version_stamp: item.version_stamp || null, expected, actual: null, status: "ok", message: "" };
    if (!fs.existsSync(absPath)) {
      entry.status = "missing";
      entry.message = `Missing file: ${item.path}`;
    } else {
      entry.actual = checksumFile(absPath);
      if (entry.actual.hex !== expected.hex || entry.actual.bytes !== expected.bytes) {
        entry.status = "mismatch";
        entry.message =
          `Checksum drift for ${item.path}: expected sha256=${expected.hex} bytes=${expected.bytes}, ` +
          `got sha256=${entry.actual.hex} bytes=${entry.actual.bytes}`;
      }
    }
    if (entry.status !== "ok") {
      if (strict || policy === "exact") failures.push(entry);
      else warnings.push(entry);
    }
    results.push(entry);
  }

  const summary = {
    ok: failures.length === 0,
    repo_root: root,
    manifest_path: relativeToRepo(root, path.resolve(manifestPath)),
    manifest_version: manifest.manifest_version || null,
    strict,
    counts: { total: results.length, passed: results.length - failures.length - warnings.length, warnings: warnings.length, failures: failures.length },
    failures,
    warnings,
    results,
  };

  if (auditCoverage) {
    const audit = discovery.auditCoverage(root, seenPaths);
    summary.coverage_audit = {
      ...audit,
      tracked: audit.tracked_total,
      note:
        "COORD-607: membership is derived by rule over the engine-managed roots, not " +
        "hand-curated. An untracked engine-managed file fails this check. Exclusions are " +
        "explicit and each carries a recorded reason; regenerate the manifest with " +
        "`node coord/scripts/template-sync-discovery.js --write`.",
    };
    if (!audit.ok) {
      summary.ok = false;
      for (const rel of audit.untracked) {
        summary.failures.push({
          path: rel,
          policy: "exact",
          status: "untracked",
          message:
            `Untracked engine-managed file: ${rel}. It is under an engine-managed root and is ` +
            "not on the reasoned exclusion list, so the manifest — and therefore " +
            "check-template-sync, gov verify-engine, and conformance attestation — cannot see it.",
        });
      }
      summary.counts.failures = summary.failures.length;
    }
  }
  return { summary };
}

// Read-only merged verdict over both surfaces. The problem strings are the old refusal wording.
function engineSurfaceProblems(pin) {
  const manifestReport = pin.verifyManifest();
  const pinReport = pin.verify();
  const problems = [];
  if (!manifestReport.ok) {
    problems.push(`check-template-sync drift: ${manifestReport.failures.map((f) => `${f.path} (${f.kind})`).join(", ")}`);
  }
  if (!pinReport.ok) {
    const driftedPaths = (pinReport.drifted_files || []).map((f) => `${f.path} (${f.kind})`);
    problems.push(
      `verify-engine drift: ${driftedPaths.length ? driftedPaths.join(", ") : pinReport.problems.map((p) => p.code).join(", ")}`
    );
  }
  return { ok: problems.length === 0, problems, manifestReport, pinReport };
}

// The one regenerate-and-verify step. Mutates ONLY the target's manifest and pin.
function regenerateAndVerify({ invokedRoot, targetRoot, manifestVersion, generatedAt, useGit = true } = {}) {
  const target = path.resolve(targetRoot || invokedRoot);
  refuseCanonicalTarget(invokedRoot, target);
  const coordDir = path.join(target, "coord");
  const manifestPath = path.join(coordDir, "TEMPLATE_SYNC_MANIFEST.json");
  const previous = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : null;
  const { manifest, dropped } = discovery.buildManifest(target, previous, { manifestVersion, useGit, now: generatedAt });
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  const pin = createEnginePin({ coordDir, fail });
  const pinned = pin.pin();
  // Re-read from disk after stamping: a manifest or pin that did not converge is refused here.
  const verdict = engineSurfaceProblems(pin);
  const coverage = discovery.auditCoverage(target, new Set(manifest.items.map((item) => item.path)), { useGit });
  const problems = [...verdict.problems];
  if (!coverage.ok) problems.push(`untracked engine-managed file(s): ${coverage.untracked.join(", ")}`);
  if (problems.length > 0) {
    // guard:engine-surface-integrity
    fail(`regenerate-and-verify refused for ${target}: ${problems.join("; ")}. The surface did not converge after stamping (COORD-958).`);
  }
  return {
    ok: true,
    target,
    manifest_path: manifestPath,
    pin_path: pin.paths.PIN_PATH,
    manifest_items: manifest.items.length,
    dropped,
    pinned_files: Object.keys(pinned.pin.files).length,
    manifest_fingerprint: pinned.pin.manifest_fingerprint,
  };
}

// Read-only counterpart of regenerateAndVerify: says whether the surface is stamped and pinned.
function verifySurface({ coordDir }) {
  const pin = createEnginePin({ coordDir, fail });
  return engineSurfaceProblems(pin);
}

module.exports = {
  EngineSurfaceRefusal,
  evaluateTemplateSync,
  engineSurfaceProblems,
  regenerateAndVerify,
  verifySurface,
  refuseCanonicalTarget,
  isTicketWorktree,
  gitToplevel,
  MANIFEST_REL,
};
